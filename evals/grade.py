#!/usr/bin/env python3
"""Grade baton-skill eval runs: grade.py <iteration-dir>

For every <eval>/<config>/ run it reads project/.baton/, project files and
outputs/{commands.log,summary.md}, checks the assertions below and writes
<run>/grading.json in the skill-creator format ({text, passed, evidence}).
"""

import json
import re
import subprocess
import sys
from pathlib import Path

# make_fixture.sh writes 8 events (6 entries + 2 replies); later events are the agent's.
FIXTURE_EVENTS = 8


def load(run: Path):
    proj = run / "project"
    events = []
    for p in sorted((proj / ".baton/events").glob("*.jsonl")):
        for line in p.read_text().splitlines():
            if line.strip():
                events.append(json.loads(line))
    events.sort(key=lambda e: e["ev"])
    threads = {}
    for e in events:
        if e["type"] == "entry":
            threads[e["id"]] = {**e, "replies": [], "status": e.get("status", "OPEN"), "closed_by": None}
        elif e["id"] in threads:
            t = threads[e["id"]]
            if e["type"] == "reply":
                t["replies"].append(e)
            elif e["type"] == "close":
                t["status"], t["closed_by"] = "CLOSED", e["from"]
    log = (run / "outputs/commands.log").read_text() if (run / "outputs/commands.log").exists() else ""
    summary = (run / "outputs/summary.md").read_text() if (run / "outputs/summary.md").exists() else ""
    cfg = json.loads((proj / ".baton/config.json").read_text())
    return proj, events, threads, log, summary, cfg


def check(text, passed, evidence):
    return {"text": text, "passed": bool(passed), "evidence": evidence}


def common(proj, events, threads, log, fixture_ev):
    out = []
    lint = subprocess.run(["baton", "lint"], cwd=proj, capture_output=True, text=True, check=False,
                          env={"BATON_ROOT": str(proj), "PATH": "/usr/bin:/bin:/opt/homebrew/bin:"
                               + str(Path.home() / ".local/bin")})
    evs = [e["ev"] for e in events]
    out.append(check("Board is intact: valid JSONL, contiguous event numbers, lint has 0 errors",
                     lint.returncode == 0 and evs == list(range(1, len(evs) + 1)),
                     lint.stdout.strip().splitlines()[-1] if lint.stdout.strip() else lint.stderr.strip()))
    banner_ok = (proj / ".baton/BOARD.md").read_text().startswith("<!-- GENERATED by baton")
    hand = [ln for ln in log.splitlines()
            if ".baton/" in ln and re.search(r"(>|\bsed\b|\btee\b|\bcp\b|\bmv\b|\brm\b|Write|Edit)", ln)
            and not ln.strip().startswith(("cat ", "head ", "tail ", "ls ", "grep "))]
    out.append(check("Never edited .baton/ files by hand (only through the baton CLI)",
                     banner_ok and not hand, "hand-edit commands: " + ("; ".join(hand) if hand else "none")))
    baton_cmds = re.findall(r"baton\s+(brief|unread|show|list|open|status|grep|guide|where|stats|post|reply|"
                            r"close|handoff|sprint|init|import|render)", log)
    first_write = next((i for i, c in enumerate(baton_cmds)
                        if c in ("post", "reply", "close", "handoff", "sprint", "init", "import")), None)
    reads_first = bool(baton_cmds) and (first_write is None or first_write > 0)
    out.append(check("Read the board before writing to it",
                     reads_first, f"baton commands in order: {' '.join(baton_cmds[:12])}"))
    mine = [(e["from"], e["kind"], e["title"]) for e in events if e["ev"] > fixture_ev and e["type"] == "entry"]
    dups = sorted({m for m in mine if mine.count(m) > 1})
    out.append(check("No duplicate entries (the same author posting the same title twice)", not dups,
                     f"duplicates: {dups}" if dups else "none"))
    return out


def new_entries(events, fixture_ev, kind=None, author=None):
    return [e for e in events if e["ev"] > fixture_ev and e["type"] == "entry"
            and (kind is None or e["kind"] == kind) and (author is None or e["from"] == author)]


def grade_frontend(proj, events, threads, log, summary, cfg, fx):
    out = []
    r = [x for x in threads["Q-002"]["replies"] if x["from"] == "frontend"]
    out.append(check("Answered qa's waiting question Q-002", r, r[0]["body"][:160] if r else "no reply from frontend"))
    qs = [e for e in new_entries(events, fx, "Q", "frontend") if "backend" in e["to"]]
    pag = [e for e in qs if re.search(r"paginat", e["title"] + e["body"], re.IGNORECASE)]
    out.append(check("Asked backend about pagination in a Q entry addressed to backend by name",
                     pag, f"{pag[0]['id']} to={pag[0]['to']}: {pag[0]['title']}" if pag else f"Q entries: {[q['id'] for q in qs]}"))
    interim = [e for e in pag if re.search(r"meanwhile|in the meantime|for now|until|assum|interim|building against|"
                                           r"proceed|default", e["body"], re.IGNORECASE)]
    out.append(check("The question states an interim choice so work can continue", interim,
                     interim[0]["body"][:200] if interim else (pag[0]["body"][:200] if pag else "no question")))
    hs = [e for e in new_entries(events, fx, "H", "frontend") if "qa" in e["to"]]
    row = json.loads((proj / ".baton/events/status.json").read_text()).get("frontend", {})
    out.append(check("Handed off to qa with `baton handoff` (H entry to qa, status row points to it)",
                     hs and row.get("handoff") == hs[-1]["id"],
                     f"H entries: {[h['id'] for h in hs]}; status row: {row}"))
    out.append(check("Hand-off body is at most 20 lines",
                     hs and len(hs[-1]["body"].splitlines()) <= 20,
                     f"{len(hs[-1]['body'].splitlines())} lines" if hs else "no hand-off"))
    q2 = threads["Q-002"]
    out.append(check("Closed qa's Q-002 after answering it", q2["status"] == "CLOSED" and r,
                     f"Q-002 {q2['status']} by {q2['closed_by']}"))
    b = threads["B-003"]
    out.append(check("Closed its own blocker B-003, which backend had fixed", b["status"] == "CLOSED",
                     f"status {b['status']} closed_by {b['closed_by']}"))
    g = (proj / "apps/web/src/Gallery.tsx").read_text()
    out.append(check("Made the code change in apps/web/src/Gallery.tsx", len(g.splitlines()) > 1, g[:120]))
    return out


def grade_orchestrator(proj, events, threads, log, summary, cfg, fx):
    out = []
    out.append(check("Started sprint S2 (config sprint is S2)", cfg["sprint"] == "S2", f"sprint={cfg['sprint']}"))
    arch = proj / ".baton/archive/BOARD-S1.md"
    out.append(check("Archived S1 via `baton sprint` (.baton/archive/BOARD-S1.md exists)", arch.exists(), str(arch.exists())))
    out.append(check("Closed the settled question Q-006 (answered by the orchestrator)",
                     threads["Q-006"]["status"] == "CLOSED", threads["Q-006"]["status"]))
    out.append(check("Closed the fixed blocker B-003", threads["B-003"]["status"] == "CLOSED", threads["B-003"]["status"]))
    out.append(check("Left qa's unanswered question Q-002 open (not bulk-closed)",
                     threads["Q-002"]["status"] == "OPEN", f"Q-002 {threads['Q-002']['status']} by {threads['Q-002']['closed_by']}"))
    out.append(check("Kept the live contract C-001 open (not superseded)",
                     threads["C-001"]["status"] == "OPEN", f"C-001 {threads['C-001']['status']}"))
    out.append(check("Summary reports Q-002 as still open going into S2", "Q-002" in summary,
                     summary[:300].replace("\n", " ")))
    out.append(check("Summary is short (at most ~15 lines)", 0 < len(summary.strip().splitlines()) <= 15,
                     f"{len(summary.strip().splitlines())} lines"))
    return out


def grade_backend(proj, events, threads, log, summary, cfg, fx):
    out = []
    d = (proj / "packages/shared/src/design.ts").read_text()
    out.append(check("Renamed thumbUrl to thumbnailUrl in design.ts", "thumbnailUrl" in d and "thumbUrl" not in d, d.strip()))
    cs = new_entries(events, fx, "C", "backend")
    ok = [c for c in cs if "packages/shared/src/design.ts" in c.get("files", [])]
    out.append(check("Posted a C (contract change) entry listing packages/shared/src/design.ts in --files", ok,
                     f"C entries: {[(c['id'], c.get('files')) for c in cs]}"))
    named = [c for c in ok if {"frontend", "qa"} <= set(c["to"])]
    out.append(check("The contract change is addressed to frontend and qa by name", named,
                     f"to={ok[0]['to']}" if ok else "no C entry"))
    cites = [c for c in ok if re.search(r"C-0*01|Q-0*06", c["body"] + c["title"] + " ".join(c.get("cites", [])))]
    out.append(check("The contract change cites C-001 or Q-006 instead of restating them", cites,
                     (ok[0]["body"][:160] + " cites=" + str(ok[0].get("cites"))) if ok else "no C entry"))
    out.append(check("Closed Q-006 as settled", threads["Q-006"]["status"] == "CLOSED",
                     f"{threads['Q-006']['status']} by {threads['Q-006']['closed_by']}"))
    out.append(check("Closed the superseded contract C-001 once the new C entry replaced it",
                     threads["C-001"]["status"] == "CLOSED", f"C-001 {threads['C-001']['status']}"))
    hs = new_entries(events, fx, "H", "backend")
    row = json.loads((proj / ".baton/events/status.json").read_text()).get("backend", {})
    out.append(check("Handed off with `baton handoff` so STATUS.md reflects the change",
                     hs and row.get("handoff") == hs[-1]["id"], f"H: {[h['id'] for h in hs]}; row: {row.get('handoff')}"))
    return out


GRADERS = {"frontend-builder-cycle": grade_frontend, "orchestrator-close-sprint": grade_orchestrator,
           "backend-contract-change": grade_backend}


def main(it: Path) -> None:
    for name, fn in GRADERS.items():
        for run in sorted(it.glob(f"eval-*-{name}/*/run-*")):
            if not (run / "project").exists():
                continue
            proj, events, threads, log, summary, cfg = load(run)
            fx = FIXTURE_EVENTS
            res = common(proj, events, threads, log, fx) + fn(proj, events, threads, log, summary, cfg, fx)
            passed = sum(r["passed"] for r in res)
            (run / "grading.json").write_text(json.dumps({
                "expectations": res,
                "summary": {"passed": passed, "failed": len(res) - passed, "total": len(res),
                            "pass_rate": round(passed / len(res), 3)}}, indent=2))
            print(f"{name:28} {run.parent.name:14} {passed}/{len(res)}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
